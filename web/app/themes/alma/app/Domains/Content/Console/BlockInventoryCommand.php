<?php

namespace App\Domains\Content\Console;

use App\Support\BlockMarkup;
use Illuminate\Console\Command;
use ReflectionClass;

/**
 * Write docs/block-inventory.md: every block, what it renders, its fields and where it is used.
 *
 * "Reuse before you build" only works if you can see what exists. This is that list, generated
 * from the code so it cannot drift: CI runs it with --check and fails when it is stale.
 *
 * Static by design. It reads block classes by reflection and scans files for references; it never
 * renders anything, so it runs without ACF or a database.
 */
class BlockInventoryCommand extends Command
{
    protected $signature = 'alma:blocks:inventory
        {--check : Fail if docs/block-inventory.md is out of date instead of writing it}';

    protected $description = 'Generate docs/block-inventory.md from app/Blocks, block views and patterns.';

    public function handle(): int
    {
        $path = base_path('docs/block-inventory.md');
        $markdown = $this->render($this->inventory());

        if ($this->option('check')) {
            if (! is_file($path) || file_get_contents($path) !== $markdown) {
                $this->error('docs/block-inventory.md is out of date. Run: wp acorn alma:blocks:inventory');

                return self::FAILURE;
            }

            $this->info('docs/block-inventory.md is current.');

            return self::SUCCESS;
        }

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        file_put_contents($path, $markdown);
        $this->info('Wrote docs/block-inventory.md.');

        return self::SUCCESS;
    }

    /**
     * @return list<array{slug: string, name: string, class: string, summary: string, fields: list<string>, usages: list<string>}>
     */
    public function inventory(): array
    {
        $rows = [];

        foreach (BlockMarkup::slugs() as $slug => $class) {
            $reflection = new ReflectionClass($class);
            $block = $reflection->newInstanceWithoutConstructor();

            $rows[] = [
                'slug' => $slug,
                'name' => (string) $reflection->getDefaultProperties()['name'],
                'class' => $reflection->getShortName(),
                'summary' => $this->summary($slug),
                'fields' => $this->fieldNames($block->fields()['fields'] ?? []),
                'usages' => $this->usages($slug, $class),
            ];
        }

        usort($rows, fn ($a, $b) => strcmp($a['slug'], $b['slug']));

        return $rows;
    }

    /**
     * @param  list<array{slug: string, name: string, class: string, summary: string, fields: list<string>, usages: list<string>}>  $rows
     */
    public function render(array $rows): string
    {
        $lines = [
            '# Block inventory',
            '',
            'Generated by `wp acorn alma:blocks:inventory`; do not edit by hand. CI fails when it is stale.',
            'Before writing markup in a pattern, find the block that already renders it here (docs/blocks.md).',
            '',
            '| Block | What it renders | Fields | Used by |',
            '| :--- | :--- | :--- | :--- |',
        ];

        foreach ($rows as $row) {
            $lines[] = sprintf(
                '| `acf/%s`<br>%s (`%s`) | %s | %s | %s |',
                $row['slug'],
                $row['name'],
                $row['class'],
                $this->cell($row['summary'] ?: '—'),
                $row['fields'] ? '`'.implode('`, `', $row['fields']).'`' : '—',
                $row['usages'] ? implode('<br>', $row['usages']) : '—',
            );
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * The first Blade comment in the block's view: the one-line description every view opens with.
     */
    private function summary(string $slug): string
    {
        $view = resource_path("views/blocks/{$slug}.blade.php");

        if (! is_file($view) || ! preg_match('/\{\{--\s*(.*?)\s*--\}\}/s', (string) file_get_contents($view), $m)) {
            return '';
        }

        return trim(preg_replace('/\s+/', ' ', $m[1]));
    }

    /**
     * @param  list<array<string, mixed>>  $fields
     * @return list<string>
     */
    private function fieldNames(array $fields, string $prefix = ''): array
    {
        $names = [];

        foreach ($fields as $field) {
            $names[] = $prefix.$field['name'];

            if (! empty($field['sub_fields'])) {
                $names = [...$names, ...$this->fieldNames($field['sub_fields'], $prefix.$field['name'].'.')];
            }
        }

        return $names;
    }

    /**
     * Files that place the block: `acf/<slug>` in markup, or BlockMarkup::block() by slug or class.
     *
     * @return list<string>
     */
    private function usages(string $slug, string $class): array
    {
        $short = (new ReflectionClass($class))->getShortName();
        $pattern = '/acf\/'.preg_quote($slug, '/').'\b|BlockMarkup::block\(\s*(?:[\'"]'.preg_quote($slug, '/').'[\'"]|\\\\?(?:App\\\\Blocks\\\\)?'.preg_quote($short, '/').'::class)/';
        $usages = [];

        foreach ($this->scannedFiles() as $file) {
            if (preg_match($pattern, (string) file_get_contents($file))) {
                $usages[] = '`'.ltrim(str_replace(base_path(), '', $file), '/').'`';
            }
        }

        sort($usages);

        return $usages;
    }

    /**
     * @return list<string>
     */
    private function scannedFiles(): array
    {
        $files = [
            ...(glob(base_path('patterns/*.php')) ?: []),
            ...(glob(resource_path('patterns/*.php')) ?: []),
        ];

        foreach (glob(resource_path('views/*.blade.php')) ?: [] as $view) {
            $files[] = $view;
        }

        return $files;
    }

    private function cell(string $text): string
    {
        return str_replace('|', '\|', $text);
    }
}
